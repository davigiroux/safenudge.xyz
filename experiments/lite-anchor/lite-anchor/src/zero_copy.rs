//! Account structs read in place from the input buffer.
//!
//! `#[account]` lays a struct out with `#[repr(C, packed)]`, so its bytes are exactly its fields
//! in order with no padding: the same bytes Borsh writes for the same fixed-size fields. That is
//! what lets a lite-anchor port read accounts an Anchor program wrote.

use pinocchio::Address;

/// A type for which every bit pattern is a valid value.
///
/// # Safety
///
/// Implementors must have no padding and no invalid bit patterns, so that any
/// `size_of::<Self>()` bytes can be reinterpreted as `Self`. `bool` and `char` do not qualify.
pub unsafe trait ZeroCopy: Copy + 'static {}

// Multi-byte integers have alignment above 1 on their own. In an account they only appear as
// fields of a `packed` struct, which has alignment 1, so the struct can sit at any offset. Reading
// such a field by value is sound; taking a reference to it is a compile error.
unsafe impl ZeroCopy for u8 {}
unsafe impl ZeroCopy for i8 {}
unsafe impl ZeroCopy for u16 {}
unsafe impl ZeroCopy for i16 {}
unsafe impl ZeroCopy for u32 {}
unsafe impl ZeroCopy for i32 {}
unsafe impl ZeroCopy for u64 {}
unsafe impl ZeroCopy for i64 {}
unsafe impl ZeroCopy for u128 {}
unsafe impl ZeroCopy for i128 {}
unsafe impl ZeroCopy for Address {}
unsafe impl<T: ZeroCopy, const N: usize> ZeroCopy for [T; N] {}

/// The 8-byte prefix that identifies an account type, as in Anchor.
pub trait Discriminator {
    const DISCRIMINATOR: [u8; 8];
}

/// An account struct generated by `#[account]`.
///
/// # Safety
///
/// Implementors must be `ZeroCopy` and have alignment 1, so a reference to one can be made from
/// any offset of an account's data. `#[account]` guarantees both with `#[repr(C, packed)]`.
pub unsafe trait AccountData: ZeroCopy + Discriminator {
    /// Bytes the account occupies, discriminator included.
    const SPACE: usize = 8 + core::mem::size_of::<Self>();
}

/// Compile-time check used by `#[account]` that each field is `ZeroCopy`.
#[doc(hidden)]
pub const fn assert_zero_copy<T: ZeroCopy>() {}

// Little-endian targets only: Borsh is little-endian, and a packed native integer must match it.
const _: () = assert!(cfg!(target_endian = "little"));
