//! Anchor-style account validation for `no_std` Solana programs.
//!
//! The macros in `lite-anchor-macros` run on the host at compile time, so they can use `std`,
//! `syn` and SHA-256 freely. Everything in this crate runs on-chain and is `no_std`: accounts are
//! zero-copy views over the input buffer, nothing is deserialized into owned values, and nothing
//! allocates.
//!
//! Error codes, discriminators and event encoding follow Anchor's conventions, so a client built
//! for an Anchor program keeps working against a port of it.
#![no_std]

// Lets `address!` expand to `::lite_anchor::...` inside this crate too.
extern crate self as lite_anchor;

pub mod accounts;
pub mod error;
pub mod event;
pub mod ix;
pub mod math;
pub mod pda;
pub mod token;
pub mod zero_copy;

pub use lite_anchor_macros::{account, address, error_code, event, program, Accounts};
pub use pinocchio;
pub use pinocchio::{error::ProgramError, AccountView, Address, ProgramResult};

/// Result type used by handlers and generated validation code.
pub type Result<T> = core::result::Result<T, ProgramError>;

/// Most accounts a lite-anchor program accepts in one instruction. Accounts past this are dropped
/// by the entrypoint. Pinocchio's default is 255, which reserves about 2 KiB of the 4 KiB entrypoint
/// stack frame for account views.
pub const MAX_ACCOUNTS: usize = 64;

/// Validated accounts for one instruction, generated by `#[derive(Accounts)]`.
pub trait Accounts: Sized {
    /// Number of accounts the struct consumes. Accounts after these are `remaining_accounts`.
    const LEN: usize;

    /// Checks every account against its declared type and constraints.
    fn try_accounts(program_id: &Address, accounts: &[AccountView]) -> Result<Self>;
}

/// What a handler receives, mirroring Anchor's `Context`.
pub struct Context<'a, T> {
    pub program_id: &'a Address,
    pub accounts: &'a mut T,
    pub remaining_accounts: &'a [AccountView],
}

/// One field of an `Accounts` struct, built from the account at its position.
pub trait FromAccountView: Sized {
    fn from_account_view(view: &AccountView, program_id: &Address) -> Result<Self>;

    /// The account this field wraps.
    fn view(&self) -> &AccountView;

    /// Address of the account this field wraps.
    #[inline(always)]
    fn address(&self) -> &Address {
        self.view().address()
    }
}

/// Returns `$err` from the enclosing function unless `$cond` holds.
#[macro_export]
macro_rules! require {
    ($cond:expr, $err:expr $(,)?) => {
        if !($cond) {
            return ::core::result::Result::Err(::core::convert::Into::into($err));
        }
    };
}

