//! Events, encoded as Anchor's `emit!` encodes them: an 8-byte discriminator followed by the
//! Borsh encoding of the fields, written to the log with `sol_log_data`.

use pinocchio::Address;

/// A field type with a fixed-size Borsh encoding.
pub trait BorshFixed {
    const SIZE: usize;

    /// Writes the encoding into `out[..Self::SIZE]`.
    fn write(&self, out: &mut [u8]);
}

macro_rules! impl_int {
    ($($t:ty),*) => {$(
        impl BorshFixed for $t {
            const SIZE: usize = core::mem::size_of::<$t>();
            #[inline(always)]
            fn write(&self, out: &mut [u8]) {
                out[..Self::SIZE].copy_from_slice(&self.to_le_bytes());
            }
        }
    )*};
}
impl_int!(u8, i8, u16, i16, u32, i32, u64, i64, u128, i128);

impl BorshFixed for bool {
    const SIZE: usize = 1;
    #[inline(always)]
    fn write(&self, out: &mut [u8]) {
        out[0] = u8::from(*self);
    }
}

impl BorshFixed for Address {
    const SIZE: usize = 32;
    #[inline(always)]
    fn write(&self, out: &mut [u8]) {
        out[..32].copy_from_slice(self.as_ref());
    }
}

/// An event struct generated by `#[event]`.
pub trait Event {
    const DISCRIMINATOR: [u8; 8];

    /// Writes the event to the transaction log.
    fn emit(&self);
}

/// Logs `data` with `sol_log_data`, which shows as one `Program data:` line.
#[inline(always)]
pub fn log_data(data: &[&[u8]]) {
    #[cfg(target_arch = "bpf")]
    // SAFETY: `sol_log_data` reads `data.len()` (pointer, length) pairs, which is the layout of a
    // `&[u8]`, from the start of the slice.
    unsafe {
        pinocchio::syscalls::sol_log_data(data.as_ptr() as *const u8, data.len() as u64);
    }
    #[cfg(not(target_arch = "bpf"))]
    let _ = data;
}
